#!/usr/bin/env -S uv run --no-project python
"""Build docs/errors.md, the error and warning codes, from the spec
cases and goldens that show them, so the list cannot drift from what
xetal says: each code, the shortest message a case records for it, and
the case or golden that shows it. With --check, fail when
docs/errors.md is not what this would write.

    scripts/py scripts/errors.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/errors.md"
HEAD = re.compile(r"^(error|warning)\[([a-z0-9-]+)\]: (.*)$")

INTRO = """# Errors and warnings

Every error and warning `xetal` gives starts with its code, which is
stable, and a message in words, then says where: the file, the line
and the column, with the line shown and the place underlined. A type
mismatch also says where each side got its type, and a common mistake
gets a `help:` line saying what to write instead. An error inside a
library also shows the line of the program that called into it.

```
error[type-mismatch]: expected Int, found Float
 --> type-errors/int-and-float.xtl:3:1
  |
3 | k + m
  | ^^^^^
  | - `k` is an Int
  |     - `m` is a Float
```

[Type errors, read](literate/type-errors.org) walks through the common
mistakes and their fixes. The table lists every code a spec case or a
golden shows, with the shortest message recorded for it and where to
see it in full. Generated by `scripts/errors.py` from `spec/` and
`reg/`.

| Code | Kind | Message (an example) | Shown by |
| ---- | ---- | -------------------- | -------- |
"""


def sources():
    """Each spec case and golden output, with the path it is cited by."""
    for path in sorted((ROOT / "spec").rglob("*.case")):
        yield path.relative_to(ROOT).as_posix(), path.read_text()
    for path in sorted((ROOT / "reg").glob("*.err")):
        yield path.relative_to(ROOT).as_posix(), path.read_text()


def codes():
    """code -> (kind, shortest message, where it is shown)."""
    found = {}
    for where, text in sources():
        for line in text.splitlines():
            m = HEAD.match(line.removeprefix("\x1b[31m").removesuffix("\x1b[0m"))
            if not m:
                continue
            kind, code, message = m.groups()
            best = found.get(code)
            if best is None or len(message) < len(best[1]):
                found[code] = (kind, message, where)
    return found


def cell(text):
    return text.replace("|", "\\|")


def render():
    rows = [
        f"| `{code}` | {kind} | {cell(message)} | [{Path(where).name}](../{where}) |"
        for code, (kind, message, where) in sorted(codes().items())
    ]
    return INTRO + "\n".join(rows) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != text:
            print("errors: docs/errors.md is not current (run scripts/py scripts/errors.py)")
            sys.exit(1)
        print(f"errors: docs/errors.md is current ({text.count(chr(10) + '| `')} codes)")
        return
    OUT.write_text(text)
    print(f"errors: wrote docs/errors.md")


if __name__ == "__main__":
    main()
